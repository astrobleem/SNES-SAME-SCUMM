#!/usr/bin/env python3
"""Emit a trusted SAMEPKG v1 directory for the native MSU-1 service.

The package is fully verified offline. Runtime code embeds only the fixed
header/directory identity and section metadata; it does not rescan the package
body on every read.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys
import zlib

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from same.package import ENTRY_SIZE, HEADER_SIZE, inspect_package


def _bytes(label: str, raw: bytes, width: int = 16) -> list[str]:
    lines = [f"{label}:"]
    for start in range(0, len(raw), width):
        lines.append("    .byte " + ",".join(f"${value:02X}" for value in raw[start:start + width]))
    return lines


def generate(
    package: Path,
    include: Path,
    manifest: Path,
    read_cases: Path | None = None,
    cases_include: Path | None = None,
) -> dict[str, object]:
    package = package.resolve()
    info = inspect_package(package, verify=True)
    raw = package.read_bytes()
    if len(raw) > 0xFFFFFFFF:
        raise ValueError("SAMEPKG package length does not fit the MSU-1 checked u32 policy")
    count = len(info.sections)
    directory_end = HEADER_SIZE + count * ENTRY_SIZE
    prefix = raw[:directory_end]
    if len(prefix) != directory_end:
        raise ValueError("package header/directory is truncated")
    lines = [
        "; Generated by tools/generate_snes_msu1_directory.py; do not edit.",
        f"SAME_MSU1_PACKAGE_LENGTH = ${len(raw):08X}",
        f"SAME_MSU1_DIRECTORY_COUNT = ${count:04X}",
        f"SAME_MSU1_TRUSTED_PREFIX_SIZE = ${len(prefix):04X}",
        f"SAME_MSU1_EXPECT_LAST_BYTE = ${raw[-1]:02X}",
        f"SAME_MSU1_EXPECT_PACKAGE_CRC32 = ${info.crc32:08X}",
        *(f"SAME_MSU1_PACKAGE_LENGTH_BYTE{i} = ${((len(raw) >> (8 * i)) & 0xff):02X}" for i in range(4)),
        "",
    ]
    for index, section in enumerate(info.sections):
        symbol = "".join(ch if ch.isalnum() else "_" for ch in section.name).upper()
        lines.extend([
            f"SAME_MSU1_SECTION_{symbol}_INDEX = ${index:04X}",
            f"SAME_MSU1_SECTION_{symbol}_OFFSET = ${section.offset:08X}",
            f"SAME_MSU1_SECTION_{symbol}_SIZE = ${section.size:08X}",
            f"SAME_MSU1_SECTION_{symbol}_CRC32 = ${section.crc32:08X}",
            "",
        ])
    lines.extend(_bytes("Same_Msu1_TrustedPrefix", prefix))
    lines.append("Same_Msu1_TrustedPrefix_End:")
    lines.extend(_bytes("Same_Msu1_SectionRecords", b"".join(
        section.offset.to_bytes(4, "little")
        + section.size.to_bytes(4, "little")
        + section.crc32.to_bytes(4, "little")
        for section in info.sections
    )))
    lines.append("Same_Msu1_SectionRecords_End:")
    include.parent.mkdir(parents=True, exist_ok=True)
    include.write_text("\n".join(lines) + "\n", encoding="utf-8")
    result: dict[str, object] = {
        "format": "same-msu1-trusted-directory",
        "version": 1,
        "package_bytes": len(raw),
        "package_sha256": hashlib.sha256(raw).hexdigest(),
        "header_directory_bytes": len(prefix),
        "header_directory_sha256": hashlib.sha256(prefix).hexdigest(),
        "package_crc32": f"{info.crc32:08x}",
        "section_count": count,
        "directory_records_bytes": count * 12,
        "sections": [section.to_dict() for section in info.sections],
        "runtime_policy": {
            "trusted_length": "compiler-generated exact expected byte length; MSU-1 exposes no general EOF register",
            "package_body_crc": "verified offline; not rescanned on each native read",
            "runtime_integrity": "exact header/directory identity plus per-request CRC32",
            "crc32_authentication": False,
        },
    }
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if (read_cases is None) != (cases_include is None):
        raise ValueError("read-cases and cases-include must be supplied together")
    if read_cases is not None and cases_include is not None:
        case_manifest = json.loads(read_cases.read_text(encoding="utf-8"))
        cases = case_manifest.get("cases")
        interleaved = case_manifest.get("interleaved_clients", [])
        if not isinstance(cases, list) or not cases:
            raise ValueError("read-case manifest must contain a non-empty cases list")
        if not isinstance(interleaved, list):
            raise ValueError("interleaved_clients must be a list")
        native_cases = list(cases)
        interleaved_summary: list[dict[str, object]] = []
        for index, request in enumerate(interleaved):
            if not isinstance(request, dict):
                raise ValueError(f"interleaved client {index} must be an object")
            try:
                client = str(request["client"])
                offset = int(request["offset"])
                length = int(request["length"])
            except (KeyError, TypeError, ValueError) as exc:
                raise ValueError(f"interleaved client {index} has invalid fields") from exc
            if not client or offset < 0 or length < 0 or offset + length > len(raw):
                raise ValueError(f"interleaved client {index} is outside the source package")
            payload = raw[offset:offset + length]
            name = f"I{client[:2]}{index + 1}"
            case = {
                "name": name,
                "offset": offset,
                "length": length,
                "expected": "OK",
                "crc32": f"{zlib.crc32(payload) & 0xFFFFFFFF:08x}",
                "expected_hex": payload[:32].hex(),
            }
            native_cases.append(case)
            interleaved_summary.append({
                "client": client,
                "native_case_index": len(native_cases) - 1,
                "offset": offset,
                "length": length,
                "crc32": case["crc32"],
                "sample_hex": case["expected_hex"],
            })
        record_size = 48
        case_lines = [
            "; Generated native read-oracle cases; copyright-free test metadata.",
            f"SAME_MSU1_TEST_CASE_COUNT = ${len(native_cases):04X}",
            f"SAME_MSU1_INTERLEAVED_CASE_START = ${len(cases):04X}",
            f"SAME_MSU1_INTERLEAVED_CASE_COUNT = ${len(interleaved):04X}",
            f"SAME_MSU1_TEST_CASE_SIZE = ${record_size:04X}",
            "Same_Msu1_TestCaseNames:",
        ]
        for case in native_cases:
            case_lines.extend(_bytes("", str(case["name"]).encode("ascii")[:8].ljust(8, b"\0"), width=8)[1:])
        case_lines.append("Same_Msu1_TestCases:")
        for case in native_cases:
            offset = int(case["offset"])
            length = int(case["length"])
            expected = case.get("expected")
            status = 0 if expected == "OK" else 1
            crc = int(case.get("crc32", "00000000"), 16)
            sample = bytes.fromhex(case.get("expected_hex") or "")[:32]
            record = (
                offset.to_bytes(4, "little")
                + length.to_bytes(4, "little")
                + crc.to_bytes(4, "little")
                + bytes((status, len(sample)))
                + sample.ljust(32, b"\0")
                + b"\0\0"
            )
            if len(record) != record_size:
                raise AssertionError("generated MSU1 test record has the wrong size")
            case_lines.extend(_bytes("", record)[1:])
        cases_include.parent.mkdir(parents=True, exist_ok=True)
        cases_include.write_text("\n".join(case_lines) + "\n", encoding="utf-8")
        result["native_read_case_count"] = len(native_cases)
        result["interleaved_native_cases"] = interleaved_summary
        manifest.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return result


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("package", type=Path)
    parser.add_argument("--include", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--read-cases", type=Path)
    parser.add_argument("--cases-include", type=Path)
    args = parser.parse_args()
    result = generate(args.package, args.include, args.manifest, args.read_cases, args.cases_include)
    print(json.dumps({key: result[key] for key in (
        "package_bytes", "package_sha256", "header_directory_bytes",
        "header_directory_sha256", "section_count",
    )}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
